# Generates src/ui/font5x7.h - a compact public-domain style 5x7 bitmap font.
# Each glyph is defined here as 7 rows of 5 chars ('#' on, '.' off) so it is
# human-verifiable. ASCII 32..126.
import io, os

G = {}
def g(code, rows):
    assert len(rows) == 7, code
    # 3-wide patterns are tolerated and right-aligned in the 5-wide cell.
    G[code] = [r if len(r) == 5 else "." * (5 - len(r)) + r for r in rows]
    assert all(len(r) == 5 for r in G[code]), code

