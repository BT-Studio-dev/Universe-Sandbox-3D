out.write("static const int kFontFirst = 32;\n")
out.write("static const int kFontLast = 126;\n\n")
out.write("static const unsigned char kFont5x7[kFontLast - kFontFirst + 1][kFontH] = {\n")
for code in range(32, 127):
    rows = G[code]
    vals = []
    for r in rows:
        v = 0
        for c in r:
            v = (v << 1) | (1 if c == '#' else 0)
        vals.append(v)
    comment = " ".join(rows)
    out.write("    { " + ", ".join(str(v) for v in vals) + " }, // '%c'  %s\n" % (
        chr(code) if 32 <= code < 127 else '?', comment))
out.write("};\n\n")
out.write("// Returns a pointer to the 7-byte glyph for `c`, or the space glyph.\n")
out.write("inline const unsigned char* fontGlyph(char c) {\n")
out.write("    unsigned char code = (unsigned char)c;\n")
out.write("    if (code < kFontFirst || code > kFontLast) code = ' ';\n")
out.write("    return kFont5x7[code - kFontFirst];\n")
out.write("}\n\n")
out.write("} // namespace us3d\n")

